// ===== LANGUAGE / i18n SYSTEM =====
window._i18nLoaded = true;
var _langData = {};
var _currentLang = 'tr';
var _langListeners = [];

var LANGUAGES = [
  { code: 'tr', name: 'Türkçe', flag: '🇹🇷' },
  { code: 'en', name: 'English', flag: '🇬🇧' }
];

function tr(key) {
  var v = _langData[key];
  if (v === undefined) { console.error('[i18n] MISSING KEY: "'+key+'" in lang "'+_currentLang+'"'); return key; }
  return v;
}

function getLanguages() {
  return LANGUAGES;
}

function getCurrentLang() {
  return _currentLang;
}

function detectSystemLanguage() {
  var lang = (navigator.language || navigator.userLanguage || '').split('-')[0];
  for (var i = 0; i < LANGUAGES.length; i++) {
    if (LANGUAGES[i].code === lang) return lang;
  }
  return 'en';
}

function onLangChange(fn) {
  _langListeners.push(fn);
}

function notifyLangChange() {
  for (var i = 0; i < _langListeners.length; i++) {
    _langListeners[i](_currentLang);
  }
}

function setLanguage(code) {
  console.log('[i18n] setLanguage called with:', code);
  var found = false;
  for (var i = 0; i < LANGUAGES.length; i++) {
    if (LANGUAGES[i].code === code) { found = true; break; }
  }
  if (!found) { console.log('[i18n] Language not found:', code); return; }
  _currentLang = code;
  _langData = _getTranslations(code);
  console.log('[i18n] Language set to:', code, '| tr("settings") =', tr('settings'));
  ls('app_language', code);
  console.log('[i18n] Saved to localStorage, reloading...');
  location.reload();
}


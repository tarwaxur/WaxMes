// Initialize language on load
(function initLang() {
  try {
    console.log('[i18n] initLang called');
    var saved = typeof ls === 'function' ? ls('app_language') : null;
    console.log('[i18n] Saved language from localStorage:', saved);
    if (saved) {
      _currentLang = saved;
    } else {
      _currentLang = detectSystemLanguage();
      console.log('[i18n] No saved lang, detected system:', _currentLang);
    }
    _langData = _getTranslations(_currentLang);
    console.log('[i18n] Initialized with lang:', _currentLang, '| tr("settings") =', tr('settings'));
    if (typeof ls === 'function') ls('app_language', _currentLang);
  } catch(e) {
    console.log('[i18n] initLang error:', e);
    _currentLang = 'tr';
    _langData = _getTranslations('tr');
  }
})();

// Auto-update settings sidebar labels when language changes
onLangChange(function() {
  document.querySelectorAll('.settings-cat').forEach(function(el) {
    var cat = el.dataset.cat;
    var labels = { profile: 'profile', theme: 'themes', language: 'language', privacy: 'privacy_security', media: 'media', danger: 'data_management', shortcuts: 'shortcuts', about: 'about' };
    var key = labels[cat];
    if (key) {
      var textNode = el.childNodes[el.childNodes.length - 1];
      if (textNode && textNode.nodeType === 3) {
        textNode.textContent = ' ' + tr(key);
      }
    }
  });
  // Re-render language section if open
  var langCat = document.querySelector('.settings-cat[data-cat="language"].active');
  if (langCat && typeof showSettingsCat === 'function') showSettingsCat('language');
});

// Translate system message previews dynamically
function translatePreview(msg) {
  if (!msg) return msg;
  var systemMsgs = {
    'Bu mesajı sildiniz': 'deleted_by_you',
    'You deleted this message': 'deleted_by_you',
    'Bu mesaj silindi': 'deleted_msg',
    'This message was deleted': 'deleted_msg',
    'Sohbet temizlendi': 'chat_cleared',
    'Chat cleared': 'chat_cleared',
    'Grup oluşturuldu': 'new_group',
    'Group created': 'new_group',
    'Grup güncellendi': 'group_updated',
    'Group updated': 'group_updated',
    '🔒 Mesaj': 'encrypted_message',
    '🔒 Encrypted': 'encrypted_message',
    '📷 Fotoğraf': 'photo',
    '📷 Photo': 'photo',
    '🎬 Video': 'video',
    '🎤 Ses': 'audio',
    '🎤 Audio': 'audio',
    '🎤 Sesli mesaj': 'voice_message',
    '🎤 Voice message': 'voice_message',
    '📤 İletildi': 'forwarded',
    '📤 Forwarded': 'forwarded'
  };
  // Voice call log: "📞 Sesli arama · 12:30 → 12:31 (1dk 5sn)"
  // Store call type neutrally and translate the label while keeping time/duration
  var callMatch = msg.match(/^📞 (Sesli arama|Voice Call)[^\d]*(\d+:\d+.*)$/);
  if (callMatch) {
    return '📞 ' + tr('voice_call') + ' · ' + callMatch[2];
  }
  // Check if msg starts with a known system prefix (emoji + text combinations)
  for (var key in systemMsgs) {
    if (msg.indexOf(key) !== -1) {
      var val = tr(systemMsgs[key]);
      // Preserve prefix emoji if present
      var emoji = msg.match(/^[📷🎬🎤🔒📤👑]/);
      return (emoji ? emoji[0]+' ' : '') + val;
    }
  }
  return msg;
}

